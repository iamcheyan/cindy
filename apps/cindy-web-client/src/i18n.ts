for (const locale of LOCALES) Object.assign(DICTS[locale], SCOPE_COPY[locale] ?? {});


export function resolveLocale(raw: string | null | undefined): Locale {
  const value = (raw ?? '').trim();
  if (CLASSICAL_BASE[value]) return CLASSICAL_BASE[value];
  const exact = LOCALES.find((locale) => locale.toLowerCase() === value.toLowerCase());
  if (exact) return exact;
  const language = value.toLowerCase().split('-')[0];
  if (language === 'zh') return value.toLowerCase().includes('tw') || value.toLowerCase().includes('hant') ? 'zh-TW' : 'zh-CN';
  if (language === 'pt') return value.toLowerCase().includes('br') ? 'pt-BR' : 'pt-PT';
  return LOCALES.find((locale) => locale.toLowerCase().split('-')[0] === language) ?? 'en';
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = DICTS[locale][key] ?? EN[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}
